#!/usr/bin/env bash
##
## run.sh - regression test: frame cleanup in omit-frame-pointers (src/stack.c).
##
## The pass removes a register save ("PUSH Rn" ... "POP Rn") that nothing uses and an
## "ISUB SP, N" whose [BP-k] locals are gone, and sees through labels nothing
## references. The conditions are in the header comment of frame_cleanup() in
## src/stack.c; each has a function here.
##   frame_remove.asm   hand-written, compiler shape: every function must lose the
##                      save, the ISUB or the whole frame its name says
##   frame_keep.asm     one refusal per function (register mentioned, CALL, [SP+k] or
##                      [BP-k] reaching the save, ...): must come out UNCHANGED
##   frame_xjump.asm    a function that jumps into another function's epilogue keeps its
##                      frame (keep_bp_jump_out) and its orphan save (keep_jump_out_save);
##                      run with -fomit-frame-pointers and -O2 only
##   clear16.asm        clear16.c, v32cc --standard --keep-data --data-base 0 -w
##                      -I ../differential: after full unrolling clear16 loses its whole frame
## frame_remove.asm and frame_keep.asm were generated by a script (a main that presets
## R4..R6, calls each function and stores R0 and R4..R6 into RAM); edit the files.
## Every input is also run in v32sim against its unoptimized self (RAM image, STRICT=1),
## which needs v32as and v32sim built next to this project.
##   shared_tail.asm    (commit d0814d8) function a jumps into the epilogue of function b: b's orphan
##                      save is not removed (RAM[201] is a's R4); run at -fomit-frame-pointers, -O1,
##                      -O2, -O3 against the unoptimized run
##   frame_holes.asm    the two neighbouring holes that commit closed: rl_b's "_return" label is
##                      jumped to from rl_a (omit-frame-pointers keeps rl_b's frame), and fs_b, whose
##                      epilogue fs_a jumps into, gets no fresh promote save. Same four flag sets.
##                      TEETH: a build of d0814d8 without return_label_private() fails
##                      -fomit-frame-pointers/-O2/-O3, one without the frame_info() check fails
##                      -O2/-O3 (RAM differs from the unoptimized run); the original optimizer fails
##                      -fomit-frame-pointers/-O2/-O3 on frame_holes.asm and on shared_tail.asm.
## Usage: ./run.sh [path/to/v32opt]     (or V32OPT=path, default ../../bin/v32opt)
##
#########################################################################
HERE="$(cd "$(dirname "$0")" && pwd)"
OPT="${1:-${V32OPT:-${HERE}/../../bin/v32opt}}"
case "${OPT}" in /*) ;; *) OPT="$(pwd)/${OPT}" ;; esac
DIFF="${HERE}/../differential"
TMP="$(mktemp -d)"
trap 'rm -rf "${TMP}"' EXIT
status=0
ncases=0
fail() { echo "FAIL: $1"; status=1; }

[ -x "${OPT}" ] || { echo "FAIL: ${OPT} is not an executable"; exit 1; }

# body of function $2 of file $1, without comments (the function runs to the next
# __function_ label that is not its own _return)
fn() {
    awk -v f="__function_$2:" '$0 == f {on=1; next} on && /^__function_/ && $0 !~ /_return:$/ {exit} on && !/^[ \t]*;/ {print}' "$1" |
        sed -e 's/^[ \t]*//' -e 's/[ \t]*$//'
}
# gone FILE FUNCTION REGEX... : no line of the function matches
gone() {
    local f="$1" name="$2" t re; shift 2
    t="$(fn "${f}" "${name}")"
    for re in "$@"; do
        ncases=$((ncases + 1))
        ! printf '%s\n' "${t}" | grep -qiE "${re}" || fail "${name}: '${re}' is still there"
    done
}
# there FILE FUNCTION REGEX... : some line of the function matches
there() {
    local f="$1" name="$2" t re; shift 2
    t="$(fn "${f}" "${name}")"
    for re in "$@"; do
        ncases=$((ncases + 1))
        printf '%s\n' "${t}" | grep -qiE "${re}" || fail "${name}: no line matches '${re}'"
    done
}
# same IN OUT FUNCTION... : the function is the same before and after
same() {
    local a="$1" b="$2" name; shift 2
    for name in "$@"; do
        ncases=$((ncases + 1))
        [ -n "$(fn "${a}" "${name}")" ] || { fail "${name}: not in ${a}"; continue; }
        [ "$(fn "${a}" "${name}")" = "$(fn "${b}" "${name}")" ] || fail "${name} was changed"
    done
}

run() {     # run INPUT OUTPUT FLAGS...
    local in="$1" out="$2"; shift 2
    "${OPT}" "${in}" "$@" -o "${out}" >/dev/null 2>&1 || fail "$(basename "${in}") $*: v32opt failed"
}

R="${HERE}/frame_remove.asm"
K="${HERE}/frame_keep.asm"
X="${HERE}/frame_xjump.asm"

# ---- what goes (omit-frame-pointers alone)
run "${R}" "${TMP}/r.asm" -fomit-frame-pointers
O="${TMP}/r.asm"
# an orphan save: PUSH and POP
gone  "${O}" orph_one          '^(push|pop) R4$'
there "${O}" orph_one          '^push BP$' '^mov R0, \[BP\+2\]$'
gone  "${O}" orph_two          '^(push|pop) R(4|5)$'
gone  "${O}" orph_partial      '^(push|pop) R4$'
there "${O}" orph_partial      '^push R5$' '^pop R5$'
# [SP+k] below the words pushed since: the save is not what it reads
gone  "${O}" orph_sp_deep      '^(push|pop) R4$'
there "${O}" orph_sp_deep      '^mov R1, \[SP\]$'
# every epilogue of the function loses its POP
gone  "${O}" two_rets          '^(push|pop) R4$'
gone  "${O}" save_other_orph   '^(push|pop) R10$'
# the unused frame: no [BP-k] left
gone  "${O}" orph_isub_both    '^isub SP' '^(push|pop) R4$'
gone  "${O}" isub_only         '^isub SP'
there "${O}" isub_only         '^push BP$'
# [SP+k] stays inside the words of a save that is kept: the ISUB goes, [SP] follows
gone  "${O}" isub_sp_in_saves  '^isub SP'
there "${O}" isub_sp_in_saves  '^push R5$' '^pop R5$' '^mov R1, \[SP\]$'
# a save goes, the ISUB stays: its locals are used
gone  "${O}" orph_keep_isub    '^(push|pop) R4$'
there "${O}" orph_keep_isub    '^isub SP, 2$' '^mov \[BP-2\], R0$'
# label that nothing references: the frame goes as well
gone  "${O}" bp_unref_label    '^push BP$' '^mov BP, SP$' '^mov SP, BP$' '^pop BP$'
# everything: ISUB, save, then the frame itself
gone  "${O}" chain_all         '^push BP$' '^mov BP, SP$' '^isub SP' '^(push|pop) R4$' '^mov SP, BP$' '^pop BP$'
ncases=$((ncases + 1))
[ "$(fn "${O}" chain_all | grep -v -e '^__function_chain_all_return:$' -e '^$' | tr '\n' ' ')" = "mov R0, 7 iadd R0, 1 ret " ] ||
    fail "chain_all: expected only 'mov R0, 7 / iadd R0, 1 / ret'"

# ---- what stays: functions that must come out unchanged
run "${K}" "${TMP}/k.asm" -fomit-frame-pointers
# keep_mentioned: R4 is used; keep_call: a CALL (the callee may clobber R4 for the caller's
# caller); keep_sp_reach: [SP] is the save; keep_bp_reach: [BP-2] is the save; keep_isub_bp:
# [BP-1] is used; keep_isub_args: the call's argument is staged in the ISUB's space with
# mov [SP], R0 (keep_isub_args2: [SP+1] likewise, next to a local); keep_label_depth: a
# label with a word pushed; keep_directive: a %define in the body; keep_escape_bp: LEA of a
# frame slot; keep_escape_sp: MOV Rx, SP; keep_sp_write: IMUL SP, 1 (keep_sp_write2: ISUB SP, R0); keep_pop_order: the
# POPs are not in reverse order of the PUSHes; keep_noframe: no PUSH BP / MOV BP, SP;
# keep_r12: only R1-R10 are removed; keep_bp_label_ref: a label that is jumped to;
# keep_falls: the function does not end with RET, JMP or HLT
same "${K}" "${TMP}/k.asm" keep_mentioned keep_call keep_sp_reach keep_bp_reach keep_isub_bp \
     keep_isub_args keep_isub_args2 keep_label_depth keep_directive keep_escape_bp keep_escape_sp \
     keep_sp_write keep_sp_write2 keep_pop_order keep_noframe keep_r12 keep_bp_label_ref keep_falls \
     clobber_r4 twice main
ncases=$((ncases + 1))
cmp -s <(grep -v '^[ \t]*;' "${K}") <(grep -v '^[ \t]*;' "${TMP}/k.asm") || fail "frame_keep.asm: the output differs from the input somewhere"
# the saves and the frames are all still there
there "${TMP}/k.asm" keep_sp_reach '^push R4$' '^pop R4$'
there "${TMP}/k.asm" keep_call '^push R4$' '^pop R4$'
there "${TMP}/k.asm" keep_isub_args '^isub SP, 2$'
there "${TMP}/k.asm" keep_isub_bp '^isub SP, 1$'

# ---- a body that jumps out of the function keeps its frame (BP is popped by the other epilogue)
run "${X}" "${TMP}/x.asm" -fomit-frame-pointers
same "${X}" "${TMP}/x.asm" keep_bp_jump_out kbjo_b keep_jump_out_save kjos_b main

# ---- the neighbouring holes of d0814d8, in text: the frame of rl_b and the epilogue of fs_b stay as they are
H="${HERE}/frame_holes.asm"
run "${H}" "${TMP}/h.asm" -fomit-frame-pointers
there "${TMP}/h.asm" rl_b '^push BP$' '^mov BP, SP$' '^mov SP, BP$' '^pop BP$'
there "${TMP}/h.asm" rl_a '^push BP$' '^jt R0, __function_rl_b_return$'
run "${H}" "${TMP}/h2.asm" -O2
gone  "${TMP}/h2.asm" fs_b '^push R([3-9]|10)$' '^pop R([3-9]|10)$'
there "${TMP}/h2.asm" fs_b '^push R1$' '^push R2$' '^pop R2$' '^pop R1$'
gone  "${TMP}/h2.asm" fs_a '^push R([3-9]|10)$'

# ---- --trigger-max=0 leaves the removable functions alone
run "${R}" "${TMP}/r0.asm" -fomit-frame-pointers --trigger-max=0
ncases=$((ncases + 1))
cmp -s <(grep -v '^[ \t]*;' "${R}") <(grep -v '^[ \t]*;' "${TMP}/r0.asm") || fail "--trigger-max=0 still removed something"
# ... and -fno-omit-frame-pointers does too
run "${R}" "${TMP}/rn.asm" -O2 -fno-omit-frame-pointers
there "${TMP}/rn.asm" orph_one '^push BP$'

# ---- clear16: fully unrolled, nothing is left of its frame; set4 still reads [BP+2]
run "${HERE}/clear16.asm" "${TMP}/c.asm" -O3
gone  "${TMP}/c.asm" clear16 '^push BP$' '^mov BP, SP$' '^isub SP' '^(push|pop) R[0-9]+$' '^mov SP, BP$' '^pop BP$'
there "${TMP}/c.asm" clear16 '^ret$'
there "${TMP}/c.asm" set4 '^push BP$' '^mov R0, \[BP\+2\]$'

# ---- every input against its unoptimized self in the simulator
cd "${DIFF}" || exit 1
V32OPT="${OPT}" WORK="${TMP}/work" STRICT=1 python3 run.py \
    --flags "-fomit-frame-pointers" --flags "-O2" --flags "-O3" \
    "${R}" "${K}" "${HERE}/clear16.asm" > "${TMP}/diff.txt" 2>&1
rc=$?
V32OPT="${OPT}" WORK="${TMP}/work3" STRICT=1 python3 run.py \
    --flags "-fomit-frame-pointers" --flags "-O1" --flags "-O2" --flags "-O3" \
    "${HERE}/shared_tail.asm" "${H}" >> "${TMP}/diff.txt" 2>&1
[ "${rc}" = 0 ] && rc=$?
V32OPT="${OPT}" WORK="${TMP}/work2" STRICT=1 python3 run.py \
    --flags "-fomit-frame-pointers" --flags "-O2" "${X}" >> "${TMP}/diff.txt" 2>&1
[ "${rc}" = 0 ] && rc=$?
ncases=$((ncases + 3 * 3 + 2 + 2 * 4))
while IFS= read -r line; do
    echo "${line}"; status=1
done < <(grep -E '^(FAIL|ERROR)' "${TMP}/diff.txt" | sed -E 's/  +/ /g' | cut -c1-160)
if [ "${rc}" != 0 ] && [ "${status}" = 0 ]; then
    fail "harness exited ${rc}: $(head -3 "${TMP}/diff.txt" | tr '\n' ' ')"
fi

if [ "${status}" = 0 ]; then
    echo "PASS: frame-cleanup (${ncases} checks)"
else
    echo "FAIL: frame-cleanup (see above)"
fi
exit "${status}"
